import { z } from "zod";
import { isHexColor } from "../shared/color.js";
import { THEMES, type Theme } from "./models.js";
import { enumField } from "./schema-primitives.js";

// Visual configuration shared by every indicator. It lives in each indicator's
// `settings`, next to the display options that already existed. Every field is
// optional and nothing is written back as a default: a configuration written for
// an earlier version is read exactly as before.

export const LAYOUTS = ["COMPACT", "DEFAULT", "EXPANDED"] as const;

// Named stacks of fonts that exist on virtually every system. Arbitrary font
// names and remote fonts are not accepted: they would not render reliably in an
// image embedded in a README.
export const FONT_FAMILIES = ["SYSTEM", "SANS_SERIF", "SERIF", "MONOSPACE"] as const;

export const FONT_WEIGHTS = [400, 500, 600, 700] as const;

export type Layout = (typeof LAYOUTS)[number];
export type FontFamily = (typeof FONT_FAMILIES)[number];
export type FontWeight = (typeof FONT_WEIGHTS)[number];

export interface ColorOverrides {
  /** `#RGB`, `#RRGGBB` or `transparent`. */
  readonly background?: string | undefined;
  /** `#RGB`, `#RRGGBB` or `transparent`. Fill of the summary tiles. */
  readonly surface?: string | undefined;
  readonly border?: string | undefined;
  /** Titles, names and numbers. */
  readonly text?: string | undefined;
  readonly secondaryText?: string | undefined;
  readonly mutedText?: string | undefined;
  /** The accent color: logo mark, bars and group headings. */
  readonly primary?: string | undefined;
  readonly success?: string | undefined;
  readonly warning?: string | undefined;
  readonly error?: string | undefined;
}

export interface TypographyOverrides {
  readonly fontFamily?: FontFamily | undefined;
  readonly titleSize?: number | undefined;
  readonly bodySize?: number | undefined;
  readonly labelSize?: number | undefined;
  readonly fontWeight?: FontWeight | undefined;
}

export interface DimensionOverrides {
  readonly width?: number | undefined;
  readonly padding?: number | undefined;
  /** Vertical space between the sections of the card. */
  readonly spacing?: number | undefined;
  readonly radius?: number | undefined;
}

export interface AppearanceSettings {
  readonly theme: Theme;
  readonly layout?: Layout | undefined;
  readonly colors?: ColorOverrides | undefined;
  readonly typography?: TypographyOverrides | undefined;
  readonly dimensions?: DimensionOverrides | undefined;
  /** Header: logo, title and profile label. Default `true`. */
  readonly showTitle?: boolean | undefined;
  /** The row of summary tiles. Default `true`. */
  readonly showSummary?: boolean | undefined;
  /** One-line descriptions under projects and skills. Default `false`. */
  readonly showDescriptions?: boolean | undefined;
  /** The "Generated by DevTrace" line. Default `true`. */
  readonly showFooter?: boolean | undefined;
}

export interface DisplayFlags {
  readonly title: boolean;
  readonly summary: boolean;
  readonly descriptions: boolean;
  readonly footer: boolean;
}

export function displayFlags(settings: AppearanceSettings): DisplayFlags {
  return {
    title: settings.showTitle ?? true,
    summary: settings.showSummary ?? true,
    descriptions: settings.showDescriptions ?? false,
    footer: settings.showFooter ?? true,
  };
}

/** Command line overrides win over the configuration file. */
export function applyAppearanceOverrides<T extends AppearanceSettings>(
  settings: T,
  overrides: { readonly theme?: Theme | undefined; readonly layout?: Layout | undefined },
): T {
  return {
    ...settings,
    ...(overrides.theme === undefined ? {} : { theme: overrides.theme }),
    ...(overrides.layout === undefined ? {} : { layout: overrides.layout }),
  };
}

const solidColor = z.string().refine(isHexColor, {
  message: "Invalid color: expected #RGB or #RRGGBB.",
});

const paintColor = z.string().refine((value) => value === "transparent" || isHexColor(value), {
  message: 'Invalid color: expected #RGB, #RRGGBB or "transparent".',
});

function whole(name: string, min: number, max: number) {
  return z
    .number(`Invalid ${name}: expected a number.`)
    .int(`Invalid ${name}: expected a whole number.`)
    .min(min, `Invalid ${name}: must be at least ${String(min)}.`)
    .max(max, `Invalid ${name}: must be at most ${String(max)}.`);
}

const colorsSchema = z.strictObject({
  background: paintColor.optional(),
  surface: paintColor.optional(),
  border: solidColor.optional(),
  text: solidColor.optional(),
  secondaryText: solidColor.optional(),
  mutedText: solidColor.optional(),
  primary: solidColor.optional(),
  success: solidColor.optional(),
  warning: solidColor.optional(),
  error: solidColor.optional(),
});

const typographySchema = z.strictObject({
  fontFamily: enumField("font family", FONT_FAMILIES).optional(),
  titleSize: whole("titleSize", 14, 32).optional(),
  bodySize: whole("bodySize", 10, 18).optional(),
  labelSize: whole("labelSize", 9, 16).optional(),
  fontWeight: z
    .literal(FONT_WEIGHTS, {
      error: `Invalid fontWeight: expected one of ${FONT_WEIGHTS.join(", ")}.`,
    })
    .optional(),
});

const dimensionsSchema = z.strictObject({
  width: whole("width", 360, 960).optional(),
  padding: whole("padding", 12, 48).optional(),
  spacing: whole("spacing", 8, 48).optional(),
  radius: whole("radius", 0, 24).optional(),
});

/** Fields added to the `settings` schema of every indicator. */
export const appearanceShape = {
  theme: enumField("theme", THEMES).default("DARK"),
  layout: enumField("layout", LAYOUTS).optional(),
  colors: colorsSchema.optional(),
  typography: typographySchema.optional(),
  dimensions: dimensionsSchema.optional(),
  showTitle: z.boolean().optional(),
  showSummary: z.boolean().optional(),
  showDescriptions: z.boolean().optional(),
  showFooter: z.boolean().optional(),
};
