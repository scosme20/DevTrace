import { describe, expect, it } from "vitest";
import { DEVTRACE_VERSION } from "../src/core/version.js";
import { computeStartupStats } from "../src/indicators/startup/stats.js";
import { renderStartupStats } from "../src/templates/startup-stats.js";
import { PALETTES } from "../src/templates/themes.js";
import { makeConfig, makeProject } from "./fixtures.js";

function render(
  projects: Record<string, unknown>[] = [makeProject()],
  overrides: Record<string, unknown> = {},
): string {
  const config = makeConfig(projects, overrides);
  return renderStartupStats(computeStartupStats(config.projects), {
    profile: config.profile,
    settings: config.settings,
    generatorVersion: "1.2.3",
  });
}

const portfolio = [
  makeProject({ id: "alpha", name: "Alpha", lifecycleStage: "LAUNCHED", status: "ACTIVE" }),
  makeProject({
    id: "beta",
    name: "Beta",
    lifecycleStage: "MVP",
    status: "PAUSED",
    repositoryUrl: "https://github.com/example/beta",
    websiteUrl: "https://beta.example.com",
  }),
];

describe("startup card structure", () => {
  it("is a well-formed standalone SVG document", () => {
    const svg = render();
    expect(svg).toMatch(/^<\?xml version="1.0" encoding="UTF-8"\?>\n<svg /);
    expect(svg.trimEnd().endsWith("</svg>")).toBe(true);
    expect(svg).toContain('xmlns="http://www.w3.org/2000/svg"');
    expect(svg).toMatch(/width="560" height="\d+" viewBox="0 0 560 \d+"/);
    expect(svg).toContain('role="img"');
    expect(svg).toContain('aria-labelledby="title desc"');
  });

  it("uses height and viewBox that agree", () => {
    const svg = render(portfolio);
    const [, height] = /height="(\d+)" viewBox="0 0 560 (\d+)"/.exec(svg) ?? [];
    const viewBoxHeight = /viewBox="0 0 560 (\d+)"/.exec(svg)?.[1];
    expect(height).toBe(viewBoxHeight);
  });

  it("has an accessible title and description with the statistics", () => {
    const svg = render(portfolio, { profile: { displayName: "Jane Doe" } });
    expect(svg).toContain('<title id="title">Startup &amp; SaaS Statistics</title>');
    expect(svg).toContain(
      '<desc id="desc">Jane Doe: 2 public projects, 1 active, 1 launched.</desc>',
    );
  });

  it("renders header, summary tiles and footer", () => {
    const svg = render(portfolio);
    for (const expected of [
      ">DevTrace<",
      ">Total Projects<",
      ">Active Projects<",
      ">Launched Projects<",
      ">Developer Portfolio<",
      ">Generated by DevTrace v1.2.3<",
    ]) {
      expect(svg).toContain(expected);
    }
  });

  it("renders the expected statistics values", () => {
    const svg = render(portfolio);
    expect(svg).toMatch(/font-size="28"[^>]*>2<\/text>/);
    expect(svg).toMatch(/font-size="28"[^>]*>1<\/text>/);
  });

  it("renders the project list with stage, status and link indicators", () => {
    const svg = render(portfolio);
    expect(svg).toContain(">Alpha<");
    expect(svg).toContain(">Beta<");
    expect(svg).toContain(">Launched<");
    expect(svg).toContain(">Paused<");
    expect(svg).toContain(">repo · site<");
  });

  it("renders the lifecycle distribution with one bar per stage", () => {
    const svg = render(portfolio);
    expect(svg).toContain(">LIFECYCLE<");
    expect(svg).toContain(">Mvp<");
    expect(svg).toContain(">Launched<");
    // Track plus fill for each of the two stages.
    expect(svg.match(/height="8"/g)).toHaveLength(4);
  });

  it("shows the empty state for an empty portfolio", () => {
    const svg = render([]);
    expect(svg).toContain(">No public projects configured.<");
    expect(svg).not.toContain(">PROJECTS<");
    expect(svg).not.toContain(">LIFECYCLE<");
  });
});

describe("startup card settings", () => {
  it("hides the project list when showProjectList is false", () => {
    const svg = render(portfolio, { settings: { showProjectList: false } });
    expect(svg).not.toContain(">PROJECTS<");
    expect(svg).not.toContain(">Alpha<");
    expect(svg).toContain(">LIFECYCLE<");
  });

  it("hides the lifecycle distribution when showLifecycleDistribution is false", () => {
    const svg = render(portfolio, { settings: { showLifecycleDistribution: false } });
    expect(svg).not.toContain(">LIFECYCLE<");
    expect(svg).toContain(">PROJECTS<");
  });

  it("hides link indicators when showLinks is false", () => {
    const svg = render(portfolio, { settings: { showLinks: false } });
    expect(svg).not.toContain("repo · site");
  });

  it("renders the dark theme by default", () => {
    const svg = render();
    expect(svg).toContain(`fill="${PALETTES.DARK.background}"`);
    expect(svg).not.toContain(PALETTES.LIGHT.background);
  });

  it("renders the light theme", () => {
    const svg = render(portfolio, { settings: { theme: "LIGHT" } });
    expect(svg).toContain(`fill="${PALETTES.LIGHT.background}"`);
    expect(svg).not.toContain(PALETTES.DARK.background);
  });

  it("makes the card taller when more sections are shown", () => {
    const height = (svg: string) => Number(/height="(\d+)" viewBox/.exec(svg)?.[1]);
    const full = height(render(portfolio));
    const minimal = height(
      render(portfolio, { settings: { showProjectList: false, showLifecycleDistribution: false } }),
    );
    expect(full).toBeGreaterThan(minimal);
  });
});

describe("startup card safety", () => {
  it("escapes user-controlled names and display names", () => {
    const svg = render([makeProject({ name: `<script>alert("x")</script> & <b>` })], {
      profile: { displayName: `</desc><script>` },
    });
    expect(svg).not.toContain("<script>");
    expect(svg).not.toContain("<b>");
    expect(svg).toContain("&lt;script&gt;");
    expect(svg).toContain("&amp;");
  });

  it("truncates very long project names", () => {
    const svg = render([makeProject({ name: "N".repeat(80) })]);
    expect(svg).not.toContain("N".repeat(40));
    expect(svg).toContain("…");
  });

  it("is deterministic and contains no scripts or external references", () => {
    const first = render(portfolio);
    expect(render(portfolio)).toBe(first);
    expect(first).not.toMatch(/<script|javascript:|onload=|href=|<image|<foreignObject/i);
  });

  it("uses the package version in the footer", () => {
    expect(DEVTRACE_VERSION).toMatch(/^\d+\.\d+\.\d+$/);
  });
});
