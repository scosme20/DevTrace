import { describe, expect, it } from "vitest";
import { computeAiEngineeringStats } from "../src/indicators/ai-engineering/stats.js";
import { renderAiEngineeringStats } from "../src/templates/ai-engineering-stats.js";
import { PALETTES } from "../src/templates/themes.js";
import {
  makeActivity,
  makeAiConfig,
  makeAiProject,
  makeModel,
  makeSkill,
  makeTokenMetric,
  makeTool,
} from "./ai-fixtures.js";

function render(overrides: Record<string, unknown> = {}): string {
  const config = makeAiConfig(overrides);
  return renderAiEngineeringStats(computeAiEngineeringStats(config), {
    profile: config.profile,
    settings: config.settings,
    generatorVersion: "1.2.3",
  });
}

const portfolio = {
  tools: [
    makeTool({ id: "claude-code", name: "Claude Code", provider: "Anthropic" }),
    makeTool({
      id: "copilot",
      name: "GitHub Copilot",
      provider: "GitHub",
      category: "IDE_ASSISTANT",
    }),
  ],
  models: [makeModel({ name: "Claude Sonnet", provider: "Anthropic", modelFamily: "Claude" })],
  skills: [
    makeSkill({
      id: "rag",
      name: "RAG",
      category: "RETRIEVAL_KNOWLEDGE",
      proficiencyLevel: "PRACTICING",
    }),
    makeSkill({
      id: "agents",
      name: "AI Agents",
      category: "AI_AGENTS",
      proficiencyLevel: "LEARNING",
    }),
  ],
  projects: [
    makeAiProject({
      name: "Doc Assistant",
      techniques: ["RAG", "TOOL_USE"],
      repositoryUrl: "https://github.com/example/doc-assistant",
    }),
  ],
};

describe("AI engineering card structure", () => {
  it("is a well-formed standalone SVG document", () => {
    const svg = render(portfolio);
    expect(svg).toMatch(/^<\?xml version="1.0" encoding="UTF-8"\?>\n<svg /);
    expect(svg.trimEnd().endsWith("</svg>")).toBe(true);
    expect(svg).toContain('xmlns="http://www.w3.org/2000/svg"');
    expect(svg).toMatch(/width="560" height="\d+" viewBox="0 0 560 \d+"/);
    expect(svg).toContain('role="img"');
    expect(svg).toContain('aria-labelledby="title desc"');
  });

  it("uses a height and viewBox that agree", () => {
    const svg = render(portfolio);
    expect(/height="(\d+)" viewBox/.exec(svg)?.[1]).toBe(/viewBox="0 0 560 (\d+)"/.exec(svg)?.[1]);
  });

  it("has an accessible title and a description with the counts", () => {
    const svg = render({ ...portfolio, profile: { displayName: "Jane Doe" } });
    expect(svg).toContain('<title id="title">AI Engineering Statistics</title>');
    expect(svg).toContain(
      '<desc id="desc">Jane Doe: 2 tools, 1 model, 2 skills, 1 project (public data only).</desc>',
    );
  });

  it("renders header, four summary tiles and footer", () => {
    const svg = render(portfolio);
    for (const expected of [
      ">DevTrace<",
      ">AI Engineering Profile<",
      ">AI Tools<",
      ">AI Models<",
      ">AI Skills<",
      ">AI Projects<",
      ">Generated by DevTrace v1.2.3<",
    ]) {
      expect(svg).toContain(expected);
    }
  });

  it("renders the expected statistics in the summary", () => {
    const svg = render(portfolio);
    const tiles = [...svg.matchAll(/font-size="28"[^>]*>(\d+)<\/text>/g)].map((match) => match[1]);
    expect(tiles).toEqual(["2", "1", "2", "1"]);
  });

  it("renders providers, tools with category, and models with family", () => {
    const svg = render(portfolio);
    expect(svg).toContain(">PROVIDERS · 2<");
    expect(svg).toContain(">Anthropic · GitHub<");
    expect(svg).toContain(">Claude Code<");
    expect(svg).toContain(">AI assistant<");
    expect(svg).toContain(">IDE assistant<");
    expect(svg).toContain(">Claude Sonnet<");
    expect(svg).toContain(">Claude<");
  });

  it("renders skills grouped by category with declared levels", () => {
    const svg = render(portfolio);
    expect(svg).toContain(">SKILLS · DECLARED LEVELS<");
    expect(svg).toContain(">AI agents<");
    expect(svg).toContain(">Retrieval &amp; knowledge<");
    expect(svg).toContain(">Practicing<");
    expect(svg).toContain(">Learning<");
    // Catalog order: AI agents is listed before Retrieval & knowledge.
    expect(svg.indexOf(">AI agents<")).toBeLessThan(svg.indexOf(">Retrieval &amp; knowledge<"));
  });

  it("renders projects with status, techniques and a link indicator", () => {
    const svg = render(portfolio);
    expect(svg).toContain(">Doc Assistant<");
    expect(svg).toContain(">Active<");
    expect(svg).toContain(">RAG · Tool use<");
    expect(svg).toContain(">repo<");
  });

  it("shows the empty state for an empty configuration", () => {
    const svg = render();
    expect(svg).toContain(">No AI engineering data to display.<");
    expect(svg).not.toContain(">TOOLS<");
  });

  it("shows the empty state when every section is disabled", () => {
    const svg = render({
      ...portfolio,
      settings: { showTools: false, showModels: false, showSkills: false, showProjects: false },
    });
    expect(svg).toContain(">No AI engineering data to display.<");
  });
});

describe("AI engineering card sections", () => {
  it.each([
    ["showTools", ">TOOLS<", ">Claude Code<"],
    ["showModels", ">MODELS<", ">Claude Sonnet<"],
    ["showSkills", ">SKILLS · DECLARED LEVELS<", ">Practicing<"],
    ["showProjects", ">PROJECTS<", ">Doc Assistant<"],
  ])("hides the section controlled by %s", (setting, heading, content) => {
    const shown = render(portfolio);
    expect(shown).toContain(heading);
    expect(shown).toContain(content);
    const hidden = render({ ...portfolio, settings: { [setting]: false } });
    expect(hidden).not.toContain(heading);
    expect(hidden).not.toContain(content);
  });

  it("hides the providers section when both tools and models are hidden", () => {
    const svg = render({ ...portfolio, settings: { showTools: false, showModels: false } });
    expect(svg).not.toContain(">PROVIDERS");
  });

  it("hides link indicators when showLinks is false", () => {
    expect(render({ ...portfolio, settings: { showLinks: false } })).not.toContain(">repo<");
  });

  it("does not render activity or token usage unless enabled", () => {
    const entities = {
      ...portfolio,
      activities: [makeActivity({ description: "ActivityText" })],
      tokenUsage: [makeTokenMetric()],
    };
    const svg = render(entities);
    expect(svg).not.toContain("ActivityText");
    expect(svg).not.toContain(">ACTIVITY");
    expect(svg).not.toContain(">TOKEN USAGE");
  });

  it("renders activity with type, involvement and provenance when enabled", () => {
    const svg = render({
      settings: { showActivity: true },
      activities: [
        makeActivity({
          activityType: "TEST_GENERATION",
          involvement: "AI_GENERATED",
          description: "Generated tests.",
          date: "2026-03-01",
          provenance: "ESTIMATED",
        }),
      ],
    });
    expect(svg).toContain(">ACTIVITY · DECLARED RECORDS<");
    expect(svg).toContain(">Test generation<");
    expect(svg).toContain(">AI-generated<");
    expect(svg).toContain(">2026-03-01 · Estimated<");
    expect(svg).toContain(">Generated tests.<");
  });

  it("renders token usage with value, period and provenance when enabled", () => {
    const svg = render({
      settings: { showTokenUsage: true },
      models: [makeModel()],
      tokenUsage: [makeTokenMetric({ source: "Provider export" })],
    });
    expect(svg).toContain(">TOKEN USAGE · REPORTED VALUES<");
    expect(svg).toContain(">1,200,000 tokens<");
    expect(svg).toContain(">Input tokens<");
    expect(svg).toContain("Anthropic · 2026-01-01 to 2026-01-31 · Declared · Provider export");
  });

  it("makes the card taller when more sections are shown", () => {
    const height = (svg: string) => Number(/height="(\d+)" viewBox/.exec(svg)?.[1]);
    expect(height(render(portfolio))).toBeGreaterThan(
      height(render({ ...portfolio, settings: { showTools: false, showModels: false } })),
    );
  });
});

describe("AI engineering card theme", () => {
  it("renders the dark theme by default", () => {
    const svg = render(portfolio);
    expect(svg).toContain(`fill="${PALETTES.DARK.background}"`);
    expect(svg).not.toContain(PALETTES.LIGHT.background);
  });

  it("renders the light theme", () => {
    const svg = render({ ...portfolio, settings: { theme: "LIGHT" } });
    expect(svg).toContain(`fill="${PALETTES.LIGHT.background}"`);
    expect(svg).not.toContain(PALETTES.DARK.background);
  });

  it("shares the design tokens of the startup card", () => {
    expect(render(portfolio)).toContain(`fill="${PALETTES.DARK.primary}"`);
  });
});

describe("AI engineering card safety", () => {
  it("escapes user-controlled text everywhere", () => {
    const svg = render({
      profile: { displayName: `</desc><script>` },
      tools: [makeTool({ name: `<script>alert("x")</script>`, provider: "A & B" })],
      models: [makeModel({ name: "<b>bold</b>", modelFamily: `"quoted"` })],
      skills: [makeSkill({ name: "<i>skill</i>" })],
      projects: [makeAiProject({ name: "<img src=x onerror=alert(1)>" })],
    });
    expect(svg).not.toMatch(/<script|<b>|<i>|<img/i);
    expect(svg).toContain("&lt;script&gt;");
    expect(svg).toContain("A &amp; B");
    expect(svg).toContain("&quot;quoted&quot;");
  });

  it("truncates very long names", () => {
    const svg = render({ tools: [makeTool({ name: "N".repeat(55) })] });
    expect(svg).not.toContain("N".repeat(40));
    expect(svg).toContain("…");
  });

  it("is deterministic and contains no scripts or external references", () => {
    const first = render(portfolio);
    expect(render(portfolio)).toBe(first);
    expect(first).not.toMatch(/<script|javascript:|onload=|href=|<image|<foreignObject/i);
  });
});
