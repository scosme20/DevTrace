// The three dashboards are one product: they must share a header, a footer, a
// frame, the same palette and the same size, in every theme and layout.

async function example(name: string): Promise<unknown> {
  return JSON.parse(await readFile(path.join(process.cwd(), "examples", name), "utf8")) as unknown;
}

function weeks() {
  const end = new Date("2026-03-15T00:00:00Z");
  return Array.from({ length: 52 }, (_, index) => {
    const start = new Date(end);
    start.setUTCDate(start.getUTCDate() - 7 * (51 - index));
    return {
      weekStart: start.toISOString().slice(0, 10),
      days: Array.from({ length: 7 }, (_unused, day) => (index + day) % 5),
    };
  });
}

function must<T>(result: Result<T>): T {
  if (!result.ok) throw new Error(result.errors.join(", "));
  return result.value;
}

const aiConfig = must(validateAiEngineeringConfig(await example("ai-engineering-dashboard.json")));
const startupConfig = must(validateStartupConfig(await example("startup-dashboard.json")));
const activityConfig = must(validateDeveloperActivityConfig({ version: 1 }));

const snapshot = makeSnapshot(
  [
    makeRepository({
      fullName: "me/alpha",
      name: "alpha",
      pushedAt: "2026-03-18T10:00:00Z",
      commitActivity: weeks(),
      languages: [{ name: "TypeScript", bytes: 900 }],
    }),
  ],
  { fetchedAt: "2026-03-19T08:00:00.000Z" },
);

function renderAll(theme: Theme, layout: (typeof LAYOUTS)[number]): Record<string, string> {
  const appearance = { theme, layout };
  const ai = { ...aiConfig.settings, ...appearance };
  const startup = { ...startupConfig.settings, ...appearance };
  const activity = { ...activityConfig.settings, ...appearance };
  const version = "0.0.0-test";
  return {
    ai: renderAiEngineeringDashboard(computeAiEngineeringStats(aiConfig), {
      profile: { displayName: "Octo" },
      settings: ai,
      generatorVersion: version,
    }),
    startup: renderStartupDashboard(computeStartupStats(startupConfig.projects), {
      profile: { displayName: "Octo" },
      settings: startup,
      generatorVersion: version,
    }),
    activity: renderDeveloperActivityDashboard(computeActivityStats(snapshot, activity), {
      profile: { displayName: "Octo" },
      settings: activity,
      generatorVersion: version,
    }),
  };
}

const attr = (svg: string, name: string): string | undefined =>
  new RegExp(`<svg [^>]*\\b${name}="([^"]*)"`).exec(svg)?.[1];

const frame = (svg: string): string | undefined =>
  /<rect x="0.5" y="0.5" width="\d+" height="\d+" rx="\d+"[^>]*\/>/
    .exec(svg)?.[0]
    ?.replace(/height="\d+"/, "");

describe.each(THEMES)("the three dashboards in the %s theme", (theme) => {
  const svgs = renderAll(theme, "DEFAULT");
  const all = Object.entries(svgs);

  it("have the same width, font and frame", () => {
    for (const [, svg] of all) {
      expect(attr(svg, "width")).toBe("880");
      expect(attr(svg, "font-family")).toBe(attr(svgs["ai"] ?? "", "font-family"));
      expect(frame(svg)).toBe(frame(svgs["ai"] ?? ""));
    }
  });

  it("have the same header brand and the same footer", () => {
    for (const [, svg] of all) {
      expect(svg).toContain(">DevTrace<");
      expect(svg).toContain(">Generated by DevTrace v0.0.0-test<");
      expect(svg).toContain(">Octo<");
    }
  });

  it("have a distinct title and description, linked for screen readers", () => {
    const titles = all.map(([, svg]) => /<title id="title">([^<]*)</.exec(svg)?.[1]);
    expect(new Set(titles).size).toBe(3);
    for (const [, svg] of all) {
      expect(attr(svg, "role")).toBe("img");
      expect(attr(svg, "aria-labelledby")).toBe("title desc");
      expect(/<desc id="desc">[^<]+</.test(svg)).toBe(true);
    }
  });

  it("use only colors from the design tokens", () => {
    const tokens = requireDashboardTokens({ theme });
    const allowed = new Set<string>([
      NO_PAINT,
      ...Object.values({ ...tokens.palette }),
      ...Object.values<string>(tokens.visual.tones),
      ...tokens.visual.series,
      ...tokens.visual.heat,
    ]);
    for (const [name, svg] of all) {
      const used = new Set(
        [...svg.matchAll(/\b(?:fill|stroke)="([^"]+)"/g)].map((m) => m[1] ?? ""),
      );
      expect(
        [...used].filter((color) => !allowed.has(color)),
        name,
      ).toEqual([]);
    }
  });

  it("are deterministic", () => {
    expect(renderAll(theme, "DEFAULT")).toEqual(svgs);
  });
});

describe.each(LAYOUTS)("the three dashboards in the %s layout", (layout) => {
  it("have the same width as each other and stay inside their own bounds", () => {
    const svgs = Object.values(renderAll("DARK", layout));
    expect(new Set(svgs.map((svg) => attr(svg, "width"))).size).toBe(1);
    for (const svg of svgs) {
      const width = Number(attr(svg, "width"));
      const height = Number(attr(svg, "height"));
      expect(attr(svg, "viewBox")).toBe(`0 0 ${String(width)} ${String(height)}`);
      const body = svg.slice(svg.indexOf("</desc>") + 7, svg.lastIndexOf("</svg>"));
      const outside = parseBoxes(
        body,
        requireDashboardTokens({ theme: "DARK", layout }).metrics,
      ).filter(
        (box) =>
          box.x0 < -0.51 || box.y0 < -0.51 || box.x1 > width + 0.51 || box.y1 > height + 0.51,
      );
      expect(outside).toEqual([]);
    }
  });
});

describe("SVG integrity and size", () => {
  const svgs = renderAll("DARK", "DEFAULT");

  it("holds no script, link, image, filter, external reference or id", () => {
    for (const svg of Object.values(svgs)) {
      expect(svg).not.toMatch(
        /<script|<style|<image|<foreignObject|<filter|<use|href=|url\(|\son\w+=/i,
      );
      // Only the two ids that title and desc need.
      expect([...svg.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1])).toEqual(["title", "desc"]);
    }
  });

  it("stays within a size budget that keeps GitHub fast", () => {
    for (const [name, svg] of Object.entries(svgs)) {
      expect(svg.length, name).toBeLessThan(45_000);
    }
  });

  it("writes no group that moves nothing and no default stroke width", () => {
    for (const svg of Object.values(svgs)) {
      expect(svg).not.toContain('transform="translate(0 0)"');
      expect(svg).not.toContain('stroke-width="1"');
    }
  });

  it("is well formed XML with balanced elements", () => {
    for (const svg of Object.values(svgs)) {
      const inner = svg.slice(
        svg.indexOf(">", svg.indexOf("<svg ")) + 1,
        svg.lastIndexOf("</svg>"),
      );
      const metrics = requireDashboardTokens({ theme: "DARK" }).metrics;
      expect(() => parseBoxes(inner, metrics)).not.toThrow();
      expect(svg.startsWith('<?xml version="1.0" encoding="UTF-8"?>\n<svg ')).toBe(true);
      expect(svg.endsWith("</svg>\n")).toBe(true);
    }
  });
});
